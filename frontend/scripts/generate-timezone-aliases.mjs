#!/usr/bin/env node
// Generates app/utils/timezoneAliases.ts from a compiled IANA tz source file
// (tzdata.zi), so the timezone picker can recognise one zone under its old and
// new names when the browser's Intl does not link them (WebKit lists
// Asia/Calcutta and resolves Asia/Kolkata to itself).
//
// Usage: node scripts/generate-timezone-aliases.mjs [path/to/tzdata.zi]
// Default source: /usr/share/zoneinfo/tzdata.zi. The source's "# version"
// line is recorded in the output. Nothing is fetched.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2] ?? "/usr/share/zoneinfo/tzdata.zi";
const output = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../app/utils/timezoneAliases.ts",
);

const lines = readFileSync(source, "utf8").split("\n");
const version = lines
  .find((line) => line.startsWith("# version "))
  ?.slice("# version ".length)
  .trim();
if (!version) throw new Error(`${source} has no "# version" line`);

// "L TARGET LINK": LINK is another name for TARGET.
const links = new Map();
for (const line of lines) {
  const [kind, target, link] = line.trim().split(/\s+/);
  if (kind === "L" && target && link) links.set(link, target);
}
if (links.size === 0) throw new Error(`${source} has no link lines`);

// Follow a link that names another link, so every entry points at a zone.
const zoneOf = (name) => {
  const seen = new Set();
  let current = name;
  while (links.has(current)) {
    if (seen.has(current)) throw new Error(`link cycle at ${name}`);
    seen.add(current);
    current = links.get(current);
  }
  return current;
};

// Quote only the names that need it, as Prettier's default output does.
const key = (name) =>
  /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
const entries = [...links.keys()]
  .sort()
  .map((link) => `  ${key(link)}: ${JSON.stringify(zoneOf(link))},`);

writeFileSync(
  output,
  `// Generated by scripts/generate-timezone-aliases.mjs from tzdata ${version}.
// Do not edit by hand: re-run the script against a newer tzdata.zi instead.

/** The tz database release this table was generated from. */
export const TZDATA_VERSION = ${JSON.stringify(version)};

/**
 * Every IANA link name and the zone it names, from the tz database's "L"
 * lines. Used only to compare zone ids; never to rewrite a stored id.
 */
export const TIMEZONE_LINKS: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`,
);
console.log(`${links.size} links from tzdata ${version} -> ${output}`);
